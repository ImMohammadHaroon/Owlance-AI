export function formatProjectMemory(projects: Project[]): string {
  if (!projects.length) {
    return `Project Memory:
No verified projects are stored yet. Do not invent past project examples.`;
  }

  const lines = projects.map((project, index) => {
    const parts = [
      `${index + 1}. ${project.name}`,
      project.purpose ? `Purpose: ${project.purpose}` : null,
      project.features ? `Features: ${project.features}` : null,
      project.tech_stack ? `Tech: ${project.tech_stack}` : null,
      project.status ? `Status: ${project.status}` : null,
      project.github_url ? `GitHub: ${project.github_url}` : null,
      project.live_url ? `Live: ${project.live_url}` : null,
      `Category: ${project.category}`,
    ].filter(Boolean);

    return parts.join("\n");
  });

  return `Project Memory (verified portfolio evidence for Mohammad Haroon):
Use these only when relevant. Prefer personal projects over learning collections unless the user asks otherwise. Never invent additional projects.

${lines.join("\n\n")}`;
}

export function buildSystemPrompt(
  module: AssistantModule,
  projects: Project[],
): string {
  return `${MODULE_PROMPTS[module]}

${formatProjectMemory(projects)}`;
}
